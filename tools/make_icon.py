#!/usr/bin/env python3
"""Generate the Synth String app icon / logo.

Minimal: six flat pastel rounded bars in a row, each a different height, all centred on the
same horizontal axis. The bars carry the letters of "string"; the five gaps between them carry
the letters of "synth". Text is converted to outlines (Inter, SIL OFL), so the SVG renders the
same everywhere without needing fonts.

    python3 tools/make_icon.py            # writes data/icons/dev.synthstring.SynthString.svg
"""

import colorsys
import random
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data/icons/dev.synthstring.SynthString.svg"
FONT_DIR = Path("/usr/share/fonts/rsms-inter-fonts")
BAR_FONT = FONT_DIR / "Inter-Bold.ttf"
GAP_FONT = FONT_DIR / "Inter-SemiBold.ttf"

SIZE = 128
MARGIN = 6.0          # left/right
BAR_W = 13.0          # bar width; the gaps take the rest
RADIUS = 4.5
MIN_H, MAX_H = 46.0, 116.0
SEED = 11             # bar heights are random but reproducible

BAR_LETTERS = "string"
GAP_LETTERS = "synth"
BAR_INK = "#2e2a3a"   # dark letters on the pastel bars
GAP_INK = "#8c8799"   # mid grey between the bars: readable on light and dark backgrounds
LETTER_H = 9.0        # x-height of the letters (px)


def hsl(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h % 1.0, l, s)
    return "#{:02x}{:02x}{:02x}".format(round(r * 255), round(g * 255), round(b * 255))


class Font:
    def __init__(self, path):
        self.font = TTFont(path)
        self.glyphs = self.font.getGlyphSet()
        self.cmap = self.font.getBestCmap()
        self.x_height = self.font["OS/2"].sxHeight

    def glyph(self, ch):
        return self.glyphs[self.cmap[ord(ch)]]

    def centred(self, ch, cx, cy, x_height):
        """Path of `ch` with its x-height scaled to `x_height`, centred horizontally on cx and
        with the x-height band centred on cy (so all letters share one optical centre line)."""
        scale = x_height / self.x_height
        pen = BoundsPen(self.glyphs)
        self.glyph(ch).draw(pen)
        xmin, _, xmax, _ = pen.bounds
        x = cx - (xmin + xmax) / 2 * scale
        baseline = cy + x_height / 2
        out = SVGPathPen(self.glyphs)
        self.glyph(ch).draw(TransformPen(out, (scale, 0, 0, -scale, x, baseline)))
        return out.getCommands()


def bar_heights(n, rng):
    """Distinct heights; neighbours differ clearly so the row reads like a waveform."""
    while True:
        hs = [round(rng.uniform(MIN_H, MAX_H)) for _ in range(n)]
        distinct = all(abs(a - b) >= 8 for i, a in enumerate(hs) for b in hs[i + 1:])
        neighbours = all(abs(a - b) >= 16 for a, b in zip(hs, hs[1:]))
        if distinct and neighbours:
            return hs


def main():
    rng = random.Random(SEED)
    bar_font, gap_font = Font(BAR_FONT), Font(GAP_FONT)
    n = len(BAR_LETTERS)
    gap = (SIZE - 2 * MARGIN - n * BAR_W) / (n - 1)
    cy = SIZE / 2
    heights = bar_heights(n, rng)
    # six pastel hues evenly around the colour wheel
    colours = [hsl(0.98 + i / n, 0.75, 0.80) for i in range(n)]

    shapes, ink_bars, ink_gaps = [], [], []
    for i, (ch, h, col) in enumerate(zip(BAR_LETTERS, heights, colours)):
        x = MARGIN + i * (BAR_W + gap)
        shapes.append(
            f'  <rect x="{x:.2f}" y="{cy - h / 2:.2f}" width="{BAR_W:.2f}" height="{h:.2f}" '
            f'rx="{RADIUS}" fill="{col}"/>'
        )
        ink_bars.append(bar_font.centred(ch, x + BAR_W / 2, cy, LETTER_H))
        if i < len(GAP_LETTERS):
            ink_gaps.append(gap_font.centred(GAP_LETTERS[i], x + BAR_W + gap / 2, cy, LETTER_H * 0.8))

    svg = "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">',
            "  <!-- generated by tools/make_icon.py – edit the script, not this file -->",
            *shapes,
            f'  <path d="{" ".join(ink_bars)}" fill="{BAR_INK}"/>',
            f'  <path d="{" ".join(ink_gaps)}" fill="{GAP_INK}"/>',
            "</svg>",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(svg)
    print(f"wrote {OUT.relative_to(ROOT)}  (bar heights {heights})")


if __name__ == "__main__":
    main()
